// Карточка одной вещи — одна форма на весь набор.
//
// Экран «одна штука крупно» есть у каждого приложения: вещь, место, поверхность,
// проект. Все четыре были написаны как телефонные — стопкой панелей по 62ch, — и
// на компьютере это узкая колонка слева и полтора пустых экрана справа.
//
// Форма, которой это решается, в наборе уже была: работа в широкой колонке,
// факты в инспекторе справа, который стоит на месте, пока работа скроллится.
// Так живут Склад, Неделя и Рецепты. Здесь она вынута отдельно, чтобы пятая
// карточка не стала пятой копией — и чтобы правка формы доезжала до всех сразу.
//
// Блоки инспектора получают имя класса аргументом: в колонке справа это его
// полосы, на телефоне — обычные панели. Панель внутри панели была бы вложенной
// карточкой, самой заметной приметой поделки.

import { html, raw, wide } from "../dom.js";

/**
 * @param {object} opts
 * @param {string} opts.head    шапка целиком, вместе с <header>
 * @param {string} opts.main    работа: панели, формы, списки
 * @param {function} [opts.side]  (cls) => блоки фактов; cls — "pane" или "insp-block"
 * @param {string} [opts.foot]  действия, которые нельзя отменить одним щелчком
 * @param {string} [opts.label] чем инспектор представляется голосом
 */
export function cardScreen({ head, main, side = null, foot = "", label = "Подробности" }) {
  /* На телефоне сначала факты, потом работа: страницу открывают, чтобы
     посмотреть, и только иногда — чтобы поправить. */
  if (!wide.matches || !side) {
    return html`<main class="screen">
      ${raw(head)}
      <div class="body">
        ${raw(side ? side("pane") : "")}
        ${raw(main)}
      </div>
      ${raw(foot)}
    </main>`;
  }

  return html`<main class="screen">
    ${raw(head)}
    <div class="split">
      <div class="table workcol">
        ${raw(main)}
        ${raw(foot)}
      </div>
      <aside class="inspector" aria-label="${label}">${raw(side("insp-block"))}</aside>
    </div>
  </main>`;
}
