// Скелет — обещание, что данные будут.
//
// Правило одно и оно жёсткое: скелет ставится только там, где приложение
// действительно чего-то ждёт снаружи — круг синка, снимок доски, чтение
// справочников из волта. Над готовыми данными скелета не бывает: состояние
// лежит в localStorage и читается мгновенно, а мигать серыми полосками поверх
// того, что уже есть, значит изображать работу, которой нет.
//
// Поэтому здесь нет «показать скелет на 300 мс для плавности». Есть только
// форма того, что грузится, — чтобы в момент прихода данных ничего не
// прыгнуло: скелет занимает столько же места, сколько займёт содержимое.

import { html, raw } from "../dom.js";

/** Несколько строк — форма списка, который сейчас приедет. */
export function skelRows(n = 4) {
  return html`<div class="skel-list" aria-hidden="true">${raw(
    Array.from({ length: n }, (_, i) =>
      `<div class="skel skel-row${i % 3 === 1 ? " skel-row--wide" : i % 3 === 2 ? " skel-row--half" : ""}"></div>`
    ).join("")
  )}</div>`;
}

/** Карточка: то, что приедет блоком, а не строками. */
export function skelCards(n = 2) {
  return html`<div class="skel-list" aria-hidden="true">${raw(
    Array.from({ length: n }, () => `<div class="skel skel-card"></div>`).join("")
  )}</div>`;
}

/**
 * Экран целиком, пока данных нет.
 *
 * Со словами: серые полоски без объяснения — это «сломалось или грузится?»,
 * и человек одинаково часто угадывает неправильно. Одна строка снимает вопрос.
 */
export function skelScreen(said, { rows = 5 } = {}) {
  return html`<div class="body">
    <p class="prose prose--muted skel-said" role="status">${said}</p>
    ${raw(skelRows(rows))}
  </div>`;
}
