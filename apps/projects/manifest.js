// Всё, что ядру нужно знать про Проекты.
//
// Приложение необычное только одним: главный файл оно **читает и не пишет**.
// Снимок доски собирается на компьютере из заметок волта, а сюда приезжает
// готовым — потому что волт остаётся единственным хранилищем, а телефон до него
// не дотягивается. Пишется ровно одна коллекция: правки, которые мост применяет
// к заметкам теми же операциями, что и сама доска.

import { declare } from "../../core/app.js";
import { blank, foldAnswered } from "./lib/model.js";

export default declare({
  key: "projects",
  name: "Проекты",
  empty: blank(),

  paths: {
    board: "Проекты/доска.json",
    edits: "Проекты/правки.json",
  },

  /* Правка с ответом отслужила: через месяц она становится обычным надгробием,
     иначе файл вырастет историей всех галочек за год. */
  collections: [{ key: "edits", fold: foldAnswered }],

  /** Снимок пишет мост. Пустой ответ не стирает вчерашний — это «не доехало». */
  singles: [{ key: "board", readOnly: true, accept: (data) => Boolean(data?.проекты) }],
});
